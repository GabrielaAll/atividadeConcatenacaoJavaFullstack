package org.example;

public class decimais {
    public static void main(String[] args) {
     // Crie variáveis para dois números decimais de valor a = 10 e b = 3 e mostre na tela: soma, subtração, multiplicação, divisão e resto.

        double ad = 10;
        double bd = 3;

        System.out.println("Tenho dois números, são eles: " + ad + " e " + bd +
                ", a soma deles é igual a: " + (ad + bd) +
                ", a multiplicação deles é igual a: " + (ad * bd) +
                ", a subtração deles é igual a: " + (ad - bd) +
                ", a divisão deles é igual a: " + (ad / bd) +
                " e o resto da divisão deles é igual a: " + (ad % bd));

    }
}
