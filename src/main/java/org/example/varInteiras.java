package org.example;

public class varInteiras {
    public static void main(String[] args){
        // 1- Crie variáveis para dois números inteiros de valor a = 10 e b = 3 e mostre na tela: soma, subtração, multiplicação, divisão e resto.

        int a = 10;
        int b = 3;

        System.out.println("Tenho dois números, são eles: " + a + " e " + b +
                ", a soma deles é igual a: " + (a + b) +
                ", a multiplicação deles é igual a: " + (a * b) +
                ", a subtração deles é igual a: " + (a - b) +
                ", a divisão deles é igual a: " + (a / b) +
                " e o resto da divisão deles é igual a: " + (a % b));
    }
}
